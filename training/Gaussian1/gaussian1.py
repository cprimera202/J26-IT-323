def hex_to_uint64(hs):
    return np.array([int(h, 16) for h in hs], dtype=np.uint64)

def popcount64(x):
    if hasattr(np, 'bitwise_count'):
        return np.bitwise_count(x)
    return np.unpackbits(x.view(np.uint8).reshape(*x.shape, 8), axis=-1).sum(-1)

