class RetinopathyDataset(Dataset):
    def __init__(self, dataframe, image_dir, transform=None):
        self.df = dataframe.reset_index(drop=True)
        self.image_dir = image_dir
        self.transform = transform

        # Build a filename lookup that handles extension case
        self.image_map = {}
        for filename in os.listdir(image_dir):
            stem, ext = os.path.splitext(filename)
            if ext.lower() in (".png", ".jpg", ".jpeg"):
                self.image_map[stem] = os.path.join(
                    image_dir, filename
                )

        # Verify every labelled image has a matching file
        missing = [
            str(image_id)
            for image_id in self.df["id_code"]
            if str(image_id) not in self.image_map
        ]

        if missing:
            raise FileNotFoundError(
                f"{len(missing)} images are missing. "
                f"Examples: {missing[:10]}"
            )

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        image_id = str(row["id_code"])

        image_path = self.image_map[image_id]

        with Image.open(image_path) as img:
            image = img.convert("RGB")

        if self.transform:
            image = self.transform(image)

        label = int(row["diagnosis"])
        return image, label


