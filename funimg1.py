import numpy as np
import torch
from sklearn.metrics import f1_score, accuracy_score
from tqdm.auto import tqdm

def run_epoch(model, loader, optimizer=None, scaler=None):
    training = optimizer is not None
    model.train(training)

    total_loss = 0.0
    all_labels = []
    all_preds = []

    for images, labels in tqdm(loader, leave=False):
        images = images.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)

        if training:
            optimizer.zero_grad(set_to_none=True)

        with torch.set_grad_enabled(training):
            with torch.autocast(
                device_type="cuda",
                dtype=torch.float16,
                enabled=(DEVICE.type == "cuda")
            ):
                outputs = model(images)
                loss = criterion(outputs, labels)

            if training:
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()

        total_loss += loss.item() * images.size(0)
        preds = outputs.argmax(dim=1)

        all_labels.extend(labels.detach().cpu().numpy())
        all_preds.extend(preds.detach().cpu().numpy())

    return {
        "loss": total_loss / len(loader.dataset),
        "accuracy": accuracy_score(all_labels, all_preds),
        "macro_f1": f1_score(
            all_labels,
            all_preds,
            labels=[0, 1, 2, 3, 4],
            average="macro",
            zero_division=0
        )
    }


def train_model(
    model_name="resnet50",
    head_epochs=2,
    max_epochs=12,
    patience=4
):
    model = build_model(model_name)
    scaler = torch.amp.GradScaler(
        "cuda",
        enabled=(DEVICE.type == "cuda")
    )

    history = []
    checkpoint_path = os.path.join(
        OUTPUT_DIR, f"{model_name}_best.pt"
    )

    # Stage 1: train classification head
    stages = [
        ("head", head_epochs, 1e-3),
        ("finetune", max_epochs, 1e-5)
    ]

    for stage_name, epochs, learning_rate in stages:
        if stage_name == "finetune":
            # Unfreeze the full network
            for param in model.parameters():
                param.requires_grad = True

            # Start fine-tuning from the best head-stage checkpoint
            if os.path.isfile(checkpoint_path):
                model.load_state_dict(
                    torch.load(
                        checkpoint_path,
                        map_location=DEVICE,
                        weights_only=True
                    )
                )

        optimizer = torch.optim.AdamW(
            filter(lambda p: p.requires_grad, model.parameters()),
            lr=learning_rate,
            weight_decay=1e-4
        )

        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            optimizer, mode="max", factor=0.5, patience=2
        )

        best_f1 = -1.0
        best_state = copy.deepcopy(model.state_dict())
        bad_epochs = 0

        for epoch in range(1, epochs + 1):
            train_metrics = run_epoch(
                model, train_loader, optimizer, scaler
            )
            val_metrics = run_epoch(model, val_loader)

            scheduler.step(val_metrics["macro_f1"])

            record = {
                "stage": stage_name,
                "epoch": epoch,
                "train_loss": train_metrics["loss"],
                "train_accuracy": train_metrics["accuracy"],
                "train_macro_f1": train_metrics["macro_f1"],
                "val_loss": val_metrics["loss"],
                "val_accuracy": val_metrics["accuracy"],
                "val_macro_f1": val_metrics["macro_f1"]
            }
            history.append(record)

            print(
                f"{stage_name} | Epoch {epoch}/{epochs} | "
                f"Train loss: {train_metrics['loss']:.4f} | "
                f"Val loss: {val_metrics['loss']:.4f} | "
                f"Val accuracy: {val_metrics['accuracy']:.4f} | "
                f"Val Macro-F1: {val_metrics['macro_f1']:.4f}"
            )

            if val_metrics["macro_f1"] > best_f1:
                best_f1 = val_metrics["macro_f1"]
                best_state = copy.deepcopy(model.state_dict())
                torch.save(best_state, checkpoint_path)
                bad_epochs = 0
            else:
                bad_epochs += 1

            if stage_name == "finetune" and bad_epochs >= patience:
                print("Early stopping: validation Macro-F1 did not improve.")
                break

        model.load_state_dict(best_state)

    history_path = os.path.join(
        OUTPUT_DIR, f"{model_name}_history.csv"
    )
    pd.DataFrame(history).to_csv(history_path, index=False)

    print("\nTraining completed.")
    print("Best checkpoint:", checkpoint_path)
    print("Training history:", history_path)

    return model, pd.DataFrame(history)

