def run_epoch(model, loader, optimizer=None, scaler=None):
    training = optimizer is not None
    model.train(training)

    total_loss = 0.0
    all_targets, all_preds = [], []

    for images, labels in tqdm(loader, leave=False):
        images = images.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)

        if training:
            optimizer.zero_grad(set_to_none=True)

        with torch.set_grad_enabled(training):
            with torch.autocast(
                device_type=DEVICE.type,
                dtype=torch.float16,
                enabled=(DEVICE.type == "cuda")
            ):
                logits = model(images)
                loss = criterion(logits, labels)

            if training:
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()

        total_loss += loss.item() * labels.size(0)
        preds = logits.argmax(dim=1)

        all_targets.extend(labels.detach().cpu().numpy())
        all_preds.extend(preds.detach().cpu().numpy())

    return {
        "loss": total_loss / len(loader.dataset),
        "macro_f1": f1_score(
            all_targets, all_preds,
            labels=classes, average="macro", zero_division=0
        ),
        "accuracy": accuracy_score(all_targets, all_preds)
    }


def train_model(model_name, head_epochs=2, max_epochs=12, patience=4):
    model, head = build_model(model_name)
    scaler = torch.amp.GradScaler(
        "cuda", enabled=(DEVICE.type == "cuda")
    )

    history = []
    best_f1 = -1.0
    best_epoch = 0
    epochs_without_improvement = 0

    checkpoint_path = os.path.join(
        OUTPUT_DIR, f"{model_name}_best.pt"
    )

    for stage in ["head", "finetune"]:
        if stage == "finetune":
            for param in model.parameters():
                param.requires_grad = True

            optimizer = torch.optim.AdamW([
                {"params": model.parameters(), "lr": 1e-5}
            ], weight_decay=1e-4)

        else:
            optimizer = torch.optim.AdamW(
                filter(lambda p: p.requires_grad, model.parameters()),
                lr=1e-3,
                weight_decay=1e-4
            )

        stage_epochs = head_epochs if stage == "head" else max_epochs

        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            optimizer, mode="max", factor=0.5, patience=2
        )

        print(f"\n{model_name} | Stage: {stage}")

        for epoch in range(stage_epochs):
            start = time.time()

            train_metrics = run_epoch(
                model, train_loader, optimizer, scaler
            )
            val_metrics = run_epoch(model, val_loader)

            scheduler.step(val_metrics["macro_f1"])

            record = {
                "model": model_name,
                "stage": stage,
                "epoch": epoch + 1,
                "train_loss": train_metrics["loss"],
                "train_macro_f1": train_metrics["macro_f1"],
                "val_loss": val_metrics["loss"],
                "val_macro_f1": val_metrics["macro_f1"],
                "val_accuracy": val_metrics["accuracy"]
            }
            history.append(record)

            print(
                f"Epoch {epoch+1}/{stage_epochs} | "
                f"train loss={train_metrics['loss']:.4f} | "
                f"val loss={val_metrics['loss']:.4f} | "
                f"val Macro-F1={val_metrics['macro_f1']:.4f} | "
                f"time={time.time()-start:.1f}s"
            )

            if val_metrics["macro_f1"] > best_f1:
                best_f1 = val_metrics["macro_f1"]
                best_epoch = len(history)

                torch.save({
                    "model_name": model_name,
                    "model_state_dict": model.state_dict(),
                    "best_val_macro_f1": best_f1,
                    "seed": SEED,
                    "img_size": IMG_SIZE
                }, checkpoint_path)

                epochs_without_improvement = 0
            else:
                epochs_without_improvement += 1

            # Do not stop the initial head-training stage early
            if stage == "finetune" and epochs_without_improvement >= patience:
                print("Early stopping: validation Macro-F1 did not improve.")
                break

        # The fine-tuning stage starts from the best checkpoint so far
        if stage == "head":
            saved = torch.load(
                checkpoint_path, map_location=DEVICE, weights_only=True
            )
            model.load_state_dict(saved["model_state_dict"])

    history_df = pd.DataFrame(history)
    history_df.to_csv(
        os.path.join(OUTPUT_DIR, f"{model_name}_history.csv"),
        index=False
    )

    print(f"Best validation Macro-F1: {best_f1:.4f}")
    print(f"Best checkpoint: {checkpoint_path}")

    del model, optimizer, scaler
    if DEVICE.type == "cuda":
        torch.cuda.empty_cache()

    return history_df

